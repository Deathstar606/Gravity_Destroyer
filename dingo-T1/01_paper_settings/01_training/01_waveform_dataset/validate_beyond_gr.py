import numpy as np
import pandas as pd
import yaml
import os
import lal

from dingo.gw.domains import build_domain
from dingo.gw.prior import build_prior_with_defaults
from dingo.gw.waveform_generator import WaveformGenerator
from dingo.gw.dataset.generate_dataset import BeyondGRWaveformGeneratorWrapper, generate_dataset
from dingo.gw.dataset.waveform_dataset import WaveformDataset
from dingo.gw.transforms import WhitenFixedASD
from dingo.gw.SVD import SVDBasis, ApplySVD

def get_expected_phase_shift(frequency_array, chirp_mass, beta0):
    """Computes the expected Beyond-GR phase shift (without modulo)."""
    mass_sec = chirp_mass * lal.MTSUN_SI
    nonzero_mask = frequency_array > 0
    f_nonzero = frequency_array[nonzero_mask]
    u = (np.pi * mass_sec * f_nonzero) ** (1.0 / 3.0)
    phase_shift = np.zeros_like(frequency_array)
    phase_shift[nonzero_mask] = beta0 * (u ** -3.0)
    return phase_shift

def test_beyond_gr_pipeline():
    """
    Validation script for the Beyond-GR data generation pipeline.
    
    DOCUMENTATION: Where is the phase injection applied?
    The phase injection is applied to the final synthesized complex polarizations 
    (h_plus and h_cross) generated by LALSimulation, immediately after generation 
    but before any dataset transformations (like Whitening or SVD).
    
    Why this is correct for this use case:
    While injecting Beyond-GR effects mode-by-mode (e.g. into the (2,2) mode directly) 
    is fundamentally correct in the GW frame, LALSimulation's frequency-domain 
    approximants (like IMRPhenomXHM) often return synthesized polarizations directly,
    bypassing exposed spherical harmonic modes. Because the dominant beyond-GR phase 
    correction primarily modifies the inspiral phase of the dominant emission, applying 
    the phase shift exp(i * DeltaPsi) globally to the complex polarizations perfectly 
    preserves the relative amplitudes and correctly shifts the phase of the frequency bins,
    matching the mathematical objective of the parameter estimation task.
    """
    settings_path = "beyond_gr_dataset_settings.yaml"
    with open(settings_path, 'r') as f:
        settings = yaml.safe_load(f)

    # For validation, let's use a small number of samples
    settings["num_samples"] = 2
    if "compression" in settings and "svd" in settings["compression"]:
        settings["compression"]["svd"]["num_training_samples"] = 2
        settings["compression"]["svd"]["num_validation_samples"] = 0

    domain = build_domain(settings["domain"])
    prior = build_prior_with_defaults(settings["intrinsic_prior"])

    # 1. Generators
    base_generator = WaveformGenerator(
        domain=domain,
        **settings["waveform_generator"],
    )
    wrapped_generator = BeyondGRWaveformGeneratorWrapper(base_generator)

    # Generate a base parameter dict
    p_df = pd.DataFrame(prior.sample(1))
    p0 = p_df.iloc[0].to_dict()

    print("=== Phase Correctness & Amplitude Preservation Tests ===")
    
    # Test multiple beta0 values
    for beta0 in [-3.2, 0.0, 3.2]:
        print(f"Testing beta0 = {beta0}...")
        p_gr = p0.copy()
        p_gr["beta0_true"] = 0.0
        
        p_inj = p0.copy()
        p_inj["beta0_true"] = beta0
        
        pol_gr = wrapped_generator.generate_hplus_hcross(p_gr.copy())
        pol_inj = wrapped_generator.generate_hplus_hcross(p_inj.copy())
        
        # Ensure finite
        assert np.all(np.isfinite(pol_gr["h_plus"])), f"GR waveform contains non-finite values for beta0={beta0}"
        assert np.all(np.isfinite(pol_inj["h_plus"])), f"Injected waveform contains non-finite values for beta0={beta0}"
        
        # Verify amplitude preservation
        np.testing.assert_allclose(
            np.abs(pol_inj["h_plus"]), np.abs(pol_gr["h_plus"]),
            err_msg=f"Amplitude not preserved for beta0={beta0}", rtol=1e-12, atol=1e-25
        )
        print(f"  [+] Amplitude preserved.")
        
        if beta0 == 0.0:
            # Verify beta0 = 0 reproduces GR exactly
            np.testing.assert_allclose(
                pol_inj["h_plus"], pol_gr["h_plus"], 
                err_msg="beta0=0 does not exactly reproduce GR waveform", rtol=1e-15, atol=1e-30
            )
            print("  [+] beta0=0 exactly reproduces GR waveform.")
        else:
            # Raw difference and relative difference
            raw_diff = np.linalg.norm(pol_inj["h_plus"] - pol_gr["h_plus"])
            rel_diff = raw_diff / np.linalg.norm(pol_gr["h_plus"])
            print(f"  [+] Raw difference norm: {raw_diff:e}")
            print(f"  [+] Relative difference: {rel_diff:e}")
            assert rel_diff > 1e-10, f"Relative difference too small ({rel_diff}) for beta0={beta0}"
            
            # Phase correctness
            nonzero_mask = np.abs(pol_gr["h_plus"]) > 1e-28
            phase_diff = np.angle(pol_inj["h_plus"][nonzero_mask]) - np.angle(pol_gr["h_plus"][nonzero_mask])
            phase_diff_unwrapped = np.unwrap(phase_diff)
            
            expected_phase = get_expected_phase_shift(domain()[nonzero_mask], p_inj["chirp_mass"], beta0)
            
            # The difference between unwrapped phase and expected phase should be a constant multiple of 2*pi
            phase_error = phase_diff_unwrapped - expected_phase
            # standard deviation should be zero if it's perfectly following the expected phase
            phase_std = np.std(phase_error)
            
            # Allow a small tolerance for numerical precision (e.g. 1e-7)
            assert phase_std < 1e-7, f"Phase shift is not constant relative to expectation. std={phase_std}"
            print("  [+] Phase correctness verified.")

    print("\n=== Multiple Chirp Mass u-definition Tests ===")
    for m_chirp in [10.0, 30.0, 50.0]:
        print(f"Testing chirp mass = {m_chirp}...")
        p_mc = p0.copy()
        p_mc["chirp_mass"] = m_chirp
        # Need to also adjust total mass roughly so generation doesn't fail due to unphysical params
        # But chirp mass is intrinsic, mass ratio is other param. Let bilby handle total_mass if needed.
        # Actually our dictionary p0 has mass_ratio and chirp_mass.
        p_gr_mc = p_mc.copy()
        p_gr_mc["beta0_true"] = 0.0
        
        p_inj_mc = p_mc.copy()
        p_inj_mc["beta0_true"] = 1.0
        
        pol_gr_mc = wrapped_generator.generate_hplus_hcross(p_gr_mc.copy())
        pol_inj_mc = wrapped_generator.generate_hplus_hcross(p_inj_mc.copy())
        
        nonzero_mask = np.abs(pol_gr_mc["h_plus"]) > 1e-28
        phase_diff = np.angle(pol_inj_mc["h_plus"][nonzero_mask]) - np.angle(pol_gr_mc["h_plus"][nonzero_mask])
        phase_diff_unwrapped = np.unwrap(phase_diff)
        expected_phase = get_expected_phase_shift(domain()[nonzero_mask], m_chirp, 1.0)
        phase_error = phase_diff_unwrapped - expected_phase
        
        assert np.std(phase_error) < 1e-7, f"Phase shift fails for m_chirp={m_chirp}. std={np.std(phase_error)}"
        print(f"  [+] Phase correct for m_chirp = {m_chirp}")

    print("\n=== Dataset Transform Tests ===")
    # Check whitening
    print("Testing Whitening...")
    whiten = WhitenFixedASD(domain, asd_file=settings["compression"]["whitening"], inverse=False)
    p_gr["beta0_true"] = 0.0
    p_inj["beta0_true"] = 1.0
    pol_gr = wrapped_generator.generate_hplus_hcross(p_gr.copy())
    pol_inj = wrapped_generator.generate_hplus_hcross(p_inj.copy())
    pol_gr_white = whiten(pol_gr)
    pol_inj_white = whiten(pol_inj)
    assert not np.any(np.isnan(pol_gr_white["h_plus"])), "Whitening produced NaNs in GR waveform"
    assert not np.any(np.isnan(pol_inj_white["h_plus"])), "Whitening produced NaNs in injected waveform"
    print("  [+] Whitening succeeds.")

    # Check SVD
    print("Testing SVD...")
    train_data = np.vstack([pol_gr_white["h_plus"], pol_inj_white["h_plus"]])
    basis = SVDBasis()
    basis.generate_basis(train_data, 2)
    svd_transform = ApplySVD(basis)
    pol_gr_svd = svd_transform(pol_gr_white)
    pol_inj_svd = svd_transform(pol_inj_white)
    assert pol_gr_svd["h_plus"].shape == (2,), "SVD application failed"
    print("  [+] SVD succeeds.")

    # Check serialization
    print("\n=== Testing Dataset Generation and Serialization ===")
    orig_uniform = np.random.uniform
    def mock_uniform(low, high, size=None):
        if size == 2:
            return np.array([0.0, 1.0])
        return orig_uniform(low, high, size)

    np.random.uniform = mock_uniform
    try:
        out_file = "test_dataset.hdf5"
        if os.path.exists(out_file):
            os.remove(out_file)
        
        dataset = generate_dataset(settings, num_processes=1)
        dataset.to_file(out_file)
        
        loaded_dataset = WaveformDataset(file_name=out_file)
        assert "beta0_true" in loaded_dataset.parameters.columns, "beta0_true missing from saved parameters"
        assert len(loaded_dataset) == 2, "Dataset length incorrect"
        
        beta0_vals = loaded_dataset.parameters["beta0_true"].values
        assert np.allclose(beta0_vals, [0.0, 1.0]), "Saved beta0_true values are incorrect"
        
        print("  [+] Serialized successfully.")
        
        if os.path.exists(out_file):
            os.remove(out_file)
    finally:
        np.random.uniform = orig_uniform

if __name__ == "__main__":
    test_beyond_gr_pipeline()
